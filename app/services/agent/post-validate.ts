import { parse, type ParserPlugin } from '@babel/parser';
import { isJsoncFile, parseJsonc } from '~/utils/jsonc';

export { parseJsonc } from '~/utils/jsonc';

export interface GeneratedFile {
  path: string;
  content: string;
}

export class MissingImportError extends Error {
  readonly filePath: string;
  readonly importSpecifier: string;

  constructor(filePath: string, importSpecifier: string) {
    super(`Missing import in ${filePath}: '${importSpecifier}' does not resolve to a generated or existing file.`);
    this.name = 'MissingImportError';
    this.filePath = filePath;
    this.importSpecifier = importSpecifier;
  }
}

export class GeneratedFileJsonError extends Error {
  readonly filePath: string;

  constructor(filePath: string, cause: unknown) {
    const message = cause instanceof Error ? cause.message : 'Invalid JSON.';
    super(`Invalid JSON in ${filePath}: ${message}`);
    this.name = 'GeneratedFileJsonError';
    this.filePath = filePath;
  }
}

/** A confirmed grammar error, distinct from an unavailable Babel syntax plugin. */
export class GeneratedFileSyntaxError extends Error {
  readonly filePath: string;
  readonly line?: number;
  readonly column?: number;

  constructor(filePath: string, diagnostic: { message: string; loc?: { line: number; column: number } }) {
    super(`Invalid source syntax in ${filePath}: ${diagnostic.message}`);
    this.name = 'GeneratedFileSyntaxError';
    this.filePath = filePath;
    this.line = diagnostic.loc?.line;
    this.column = diagnostic.loc?.column;
  }
}

const SOURCE_FILE_EXTENSIONS = new Set(['.js', '.jsx', '.ts', '.tsx', '.mjs', '.cjs']);

const JSON_FILE_EXTENSIONS = new Set(['.json']);

/*
 * Lockfiles are machine-generated dependency manifests, not authored source.
 * They are regenerated by the package manager on install, are excluded from
 * project-storage sync, and are stripped from AI streams — so a truncated or
 * otherwise malformed lockfile (e.g. a cached template seeded with a partial
 * write) must never hard-fail validation. Doing so threw GeneratedFileJsonError
 * and blocked the preview from ever starting, surfacing as a dead "Preview
 * Error: Invalid JSON in package-lock.json: Unexpected end of JSON input" with
 * no path to recovery. npm-shrinkwrap.json / package-lock.json are the only
 * JSON lockfiles; the others (yarn.lock, pnpm-lock.yaml, bun.lockb) aren't
 * `.json` and were never validated, but we list them so the intent is explicit.
 */
const VALIDATION_IGNORED_FILENAMES = new Set([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'yarn.lock',
  'pnpm-lock.yaml',
  'bun.lock',
  'bun.lockb',
]);

const VALIDATION_IGNORED_DIRECTORIES = new Set([
  '.cache',
  '.git',
  '.next',
  '.turbo',
  '.vite',
  'build',
  'coverage',
  'dist',
  'node_modules',
  'out',
]);

const RESOLVABLE_EXTENSIONS = [
  '',
  '.ts',
  '.tsx',
  '.js',
  '.jsx',
  '.mjs',
  '.cjs',
  '.json',
  '.css',
  '.scss',
  '.sass',
  '.less',
  '.svg',
  '.png',
  '.jpg',
  '.jpeg',
  '.webp',
  '.gif',
];

function normalizeGeneratedPath(filePath: string) {
  return filePath
    .replaceAll('\\', '/')
    .replace(/^\/?(?:home\/project|workspace)\//, '')
    .replace(/^\/+/, '');
}

function dirname(filePath: string) {
  const normalized = normalizeGeneratedPath(filePath);
  const lastSlash = normalized.lastIndexOf('/');

  return lastSlash === -1 ? '' : normalized.slice(0, lastSlash);
}

function normalizeSegments(filePath: string) {
  const segments: string[] = [];

  for (const segment of filePath.split('/')) {
    if (!segment || segment === '.') {
      continue;
    }

    if (segment === '..') {
      segments.pop();
      continue;
    }

    segments.push(segment);
  }

  return segments.join('/');
}

function extensionOf(filePath: string) {
  const basename = filePath.split('/').pop() ?? '';
  const dotIndex = basename.lastIndexOf('.');

  return dotIndex === -1 ? '' : basename.slice(dotIndex);
}

function isIgnoredValidationPath(filePath: string) {
  return normalizeGeneratedPath(filePath)
    .split('/')
    .some((segment) => VALIDATION_IGNORED_DIRECTORIES.has(segment));
}

function isSourceFile(filePath: string) {
  return SOURCE_FILE_EXTENSIONS.has(extensionOf(filePath));
}

/*
 * Pick `@babel/parser` plugins by file extension. Enabling `jsx` on a plain
 * `.ts` file makes the parser treat `<MyType>value` (legacy TS type assertion)
 * or a generic like `<T>(x: T) => x` as the opening of a JSX tag, which then
 * fails with "Unexpected token, expected ';'". The `typescript` plugin is the
 * mirror image — never apply it to plain `.js`/`.jsx`/`.mjs`/`.cjs`.
 */
function pluginsForExtension(filePath: string): ParserPlugin[] {
  const extension = extensionOf(filePath).toLowerCase();
  const plugins: ParserPlugin[] = ['importAttributes'];

  if (extension === '.ts' || extension === '.tsx') {
    plugins.push('typescript');
  }

  if (extension === '.tsx' || extension === '.jsx' || extension === '.js' || extension === '.mjs') {
    plugins.push('jsx');
  }

  return plugins;
}

function isJsonFile(filePath: string) {
  return JSON_FILE_EXTENSIONS.has(extensionOf(filePath));
}

function basenameOf(filePath: string) {
  return normalizeGeneratedPath(filePath).split('/').pop() ?? '';
}

function isLockfile(filePath: string) {
  return VALIDATION_IGNORED_FILENAMES.has(basenameOf(filePath));
}

function isRelativeOrRootImport(specifier: string) {
  return specifier.startsWith('.') || specifier.startsWith('/');
}

function addResolutionCandidates(candidates: Set<string>, basePath: string) {
  for (const extension of RESOLVABLE_EXTENSIONS) {
    candidates.add(`${basePath}${extension}`);
  }

  for (const extension of RESOLVABLE_EXTENSIONS.filter(Boolean)) {
    candidates.add(`${basePath}/index${extension}`);
  }

  /*
   * `.d.ts` ambient declaration files are a normal TS pattern. `extensionOf`
   * sees only the trailing `.ts`, so the generic `${basePath}.ts` candidate
   * never matches a file literally named `types.d.ts`, and a valid
   * `import type { Foo } from './types'` would be flagged as a missing import.
   * Add the declaration-file variants explicitly.
   */
  candidates.add(`${basePath}.d.ts`);
  candidates.add(`${basePath}/index.d.ts`);
}

function resolveImportCandidates(specifier: string, importerPath: string) {
  const candidates = new Set<string>();

  if (specifier.startsWith('/')) {
    /*
     * A leading-'/' specifier is NOT a filesystem-absolute path here. In
     * Vite/Astro/SvelteKit it resolves from the dev-server root, i.e. the
     * project's public/ directory (e.g. `import logo from '/vite.svg'` →
     * public/vite.svg) or, for source assets, the project root. Treating the
     * stripped path as the only candidate (e.g. 'vite.svg') made resolveImport
     * return undefined and threw MissingImportError, dropping the agent's file
     * write. Offer both the public/-relative and root-relative candidates.
     */
    const stripped = normalizeGeneratedPath(specifier);

    addResolutionCandidates(candidates, stripped);
    addResolutionCandidates(candidates, normalizeSegments(`public/${stripped}`));

    return [...candidates];
  }

  const basePath = normalizeSegments([dirname(importerPath), specifier].filter(Boolean).join('/'));

  addResolutionCandidates(candidates, basePath);

  return [...candidates];
}

export function resolveImport(specifier: string, importerPath: string, allFiles: Map<string, string>) {
  if (!isRelativeOrRootImport(specifier)) {
    return undefined;
  }

  for (const candidate of resolveImportCandidates(specifier, importerPath)) {
    if (allFiles.has(normalizeGeneratedPath(candidate))) {
      return normalizeGeneratedPath(candidate);
    }
  }

  return undefined;
}

/*
 * True when `specifier` points at a DIRECTORY that has direct sibling source
 * modules but no index yet — a barrel import (`import { X } from './components'`)
 * the preview repair will resolve by synthesizing src/components/index.ts. Such
 * an import must NOT hard-fail validation: doing so marks the importer (e.g.
 * App.tsx) 'failed', which then drops it from the validation set so its OWN
 * importers (main.tsx → './App') cascade-fail even though the file exists.
 */
export function importResolvesToPopulatedDirectory(
  specifier: string,
  importerPath: string,
  allFiles: Map<string, string>,
): boolean {
  if (specifier.startsWith('/')) {
    return false;
  }

  const basePath = normalizeSegments([dirname(importerPath), specifier].filter(Boolean).join('/'));

  if (!basePath) {
    return false;
  }

  const prefix = `${basePath}/`;

  for (const filePath of allFiles.keys()) {
    if (!filePath.startsWith(prefix)) {
      continue;
    }

    // Direct children only (a barrel re-exports its own directory's modules).
    if (filePath.slice(prefix.length).includes('/')) {
      continue;
    }

    if (isSourceFile(filePath) && !/(?:^|\/)index\.[^/]+$/.test(filePath)) {
      return true;
    }
  }

  return false;
}

export async function validateImports(file: GeneratedFile, allFiles: Map<string, string>) {
  const normalizedPath = normalizeGeneratedPath(file.path);

  if (!isSourceFile(normalizedPath)) {
    return;
  }

  let ast: ReturnType<typeof parse>;

  try {
    ast = parse(file.content, {
      // CommonJS uses Node's function wrapper, which permits top-level return.
      sourceType: normalizedPath.endsWith('.cjs') ? 'commonjs' : 'module',
      plugins: pluginsForExtension(normalizedPath),
    });
  } catch (error) {
    const diagnostic = error as {
      code?: string;
      reasonCode?: string;
      missingPlugin?: unknown;
      message: string;
      loc?: { line: number; column: number };
    };

    // Missing parser support is not proof that authored source has invalid grammar.
    if (
      diagnostic?.code === 'BABEL_PARSER_SYNTAX_ERROR' &&
      ['MissingPlugin', 'MissingOneOfPlugins'].includes(diagnostic.reasonCode ?? '') &&
      Array.isArray(diagnostic.missingPlugin) &&
      diagnostic.missingPlugin.length > 0
    ) {
      console.warn(`[agent post-validate] Unsupported parser plugin for ${normalizedPath}: ${diagnostic.message}`);
      return;
    }

    if (
      diagnostic?.code === 'BABEL_PARSER_SYNTAX_ERROR' ||
      diagnostic?.code === 'BABEL_PARSER_SOURCETYPE_MODULE_REQUIRED'
    ) {
      throw new GeneratedFileSyntaxError(normalizedPath, diagnostic);
    }

    // An unexpected validator failure must not authorize an unvalidated write either.
    throw error;
  }

  for (const node of ast.program.body) {
    /*
     * `import X from './m'`, `export { X } from './m'` and `export * from './m'`
     * all reference an external module via `node.source` and must be validated
     * identically. Babel parses the two re-export forms as ExportNamedDeclaration
     * / ExportAllDeclaration, NOT ImportDeclaration, so checking only the latter
     * let a broken re-export (`export { Button } from './Missing'`) slip past
     * while the equivalent plain import was caught. A local `export const x = 1`
     * has `node.source === null` and is skipped below.
     */
    const isModuleReference =
      node.type === 'ImportDeclaration' ||
      node.type === 'ExportNamedDeclaration' ||
      node.type === 'ExportAllDeclaration';

    if (!isModuleReference || node.source == null) {
      continue;
    }

    const specifier = node.source.value;

    if (typeof specifier !== 'string' || !isRelativeOrRootImport(specifier)) {
      continue;
    }

    /*
     * Leading-'/' specifiers resolve from the dev-server root / public
     * directory in Vite/Astro/SvelteKit, not from authored source. The real
     * asset (e.g. public/vite.svg) usually lives on disk in the template and
     * is never part of the generated/existing file map, so a hard-fail here
     * would wrongly drop the agent's write. We still try to resolve them (to
     * keep resolveImport useful), but only relative ('.'-prefixed) imports —
     * which must point at authored files — are allowed to block the patch.
     */
    if (specifier.startsWith('/')) {
      continue;
    }

    if (!resolveImport(specifier, normalizedPath, allFiles)) {
      /*
       * A barrel import of a directory with sibling modules but no index yet is
       * satisfiable — the preview repair synthesizes the barrel. Don't hard-fail
       * (which would cascade: the importer is dropped from the set and ITS
       * importers then fail too). Only a specifier resolving to neither a file
       * nor a populated directory is a genuine missing import.
       */
      if (importResolvesToPopulatedDirectory(specifier, normalizedPath, allFiles)) {
        continue;
      }

      throw new MissingImportError(normalizedPath, specifier);
    }
  }
}

export async function validateGeneratedFile(file: GeneratedFile, allFiles: Map<string, string>) {
  const normalizedPath = normalizeGeneratedPath(file.path);

  if (isIgnoredValidationPath(normalizedPath) || isLockfile(normalizedPath)) {
    return;
  }

  if (isJsonFile(normalizedPath)) {
    try {
      if (isJsoncFile(normalizedPath)) {
        parseJsonc(file.content);
      } else {
        JSON.parse(file.content);
      }
    } catch (error) {
      throw new GeneratedFileJsonError(normalizedPath, error);
    }

    return;
  }

  await validateImports(file, allFiles);
}

export async function validateGeneratedFiles(files: GeneratedFile[], existingFiles = new Map<string, string>()) {
  const allFiles = new Map<string, string>();

  for (const [filePath, content] of existingFiles.entries()) {
    allFiles.set(normalizeGeneratedPath(filePath), content);
  }

  for (const file of files) {
    allFiles.set(normalizeGeneratedPath(file.path), file.content);
  }

  await Promise.all(files.map((file) => validateGeneratedFile(file, allFiles)));
}

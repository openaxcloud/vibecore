export function getBaseChatAstCopy(language?: string | null): BaseChatAstCopy {
  return normalizeSupportedLanguage(language) === 'fr' ? baseChatAstFr : baseChatAstEn;
}

export function formatBaseChatAstCopy(
  template: string,
  values: Readonly<Record<string, string | number | bigint>> = {},
): string {
  return template.replace(/\{([A-Za-z_][A-Za-z0-9_]*)\}/gu, (token, key: string) => {
    const value = values[key];

    return value === undefined ? token : String(value);
  });
}

export function formatBaseChatAstPlural(
  language: string | null | undefined,
  count: number,
  templates: Readonly<{ one: string; other: string }>,
  values: Readonly<Record<string, string | number | bigint>> = {},
): string {
  const locale = normalizeSupportedLanguage(language) === 'fr' ? 'fr-FR' : 'en-US';
  const suffix = new Intl.PluralRules(locale).select(count) === 'one' ? 'one' : 'other';

  return formatBaseChatAstCopy(templates[suffix], {
    ...values,
    count: new Intl.NumberFormat(locale).format(count),
  });
}

type BaseChatAstDateInput = Date | string | number;

export function baseChatAstLocale(language?: string | null): 'en-US' | 'fr-FR' {
  return normalizeSupportedLanguage(language) === 'fr' ? 'fr-FR' : 'en-US';
}

function validBaseChatAstDate(value: BaseChatAstDateInput): Date | null {
  const date = value instanceof Date ? value : new Date(value);

  return Number.isNaN(date.getTime()) ? null : date;
}

export function formatBaseChatAstNumber(
  language: string | null | undefined,
  value: number | bigint,
  options?: Intl.NumberFormatOptions,
): string {
  return new Intl.NumberFormat(baseChatAstLocale(language), options).format(value);
}

export function formatBaseChatAstDate(
  language: string | null | undefined,
  value: BaseChatAstDateInput,
  options: Intl.DateTimeFormatOptions = { dateStyle: 'medium' },
): string | null {
  const date = validBaseChatAstDate(value);

  return date ? new Intl.DateTimeFormat(baseChatAstLocale(language), options).format(date) : null;
}

export function formatBaseChatAstTime(
  language: string | null | undefined,
  value: BaseChatAstDateInput,
  options: Intl.DateTimeFormatOptions = { timeStyle: 'short' },
): string | null {
  const date = validBaseChatAstDate(value);

  return date ? new Intl.DateTimeFormat(baseChatAstLocale(language), options).format(date) : null;
}

export function formatBaseChatAstDateTime(
  language: string | null | undefined,
  value: BaseChatAstDateInput,
  options: Intl.DateTimeFormatOptions = { dateStyle: 'medium', timeStyle: 'short' },
): string | null {
  const date = validBaseChatAstDate(value);

  return date ? new Intl.DateTimeFormat(baseChatAstLocale(language), options).format(date) : null;
}

export function formatBaseChatAstRelativeTime(
  language: string | null | undefined,
  value: BaseChatAstDateInput,
  now = Date.now(),
): string | null {
  const date = validBaseChatAstDate(value);

  if (!date) {
    return null;
  }

  const deltaSeconds = Math.round((date.getTime() - now) / 1_000);
  const absoluteSeconds = Math.abs(deltaSeconds);

  const units: Array<readonly [Intl.RelativeTimeFormatUnit, number]> = [
    ['year', 365 * 24 * 60 * 60],
    ['month', 30 * 24 * 60 * 60],
    ['day', 24 * 60 * 60],
    ['hour', 60 * 60],
    ['minute', 60],
  ];

  for (const [unit, size] of units) {
    if (absoluteSeconds >= size) {
      return new Intl.RelativeTimeFormat(baseChatAstLocale(language), { numeric: 'auto' }).format(
        Math.round(deltaSeconds / size),
        unit,
      );
    }
  }

  return new Intl.RelativeTimeFormat(baseChatAstLocale(language), { numeric: 'auto' }).format(0, 'second');
}

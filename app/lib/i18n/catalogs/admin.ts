export type AdminTranslationKey = keyof typeof adminCatalog.en;

export function translateAdmin(
  language: SupportedLanguage | 'en' | 'fr' | undefined,
  key: AdminTranslationKey,
  values?: Readonly<Record<string, string | number>>,
): string {
  const locale = language === 'fr' ? 'fr' : 'en';

  const template =
    adminCatalog[locale][key] ?? adminCatalog.en[key] ?? adminCatalog[locale]['admin.standalone.contentUnavailable'];

  if (!values) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  );
}

export function getKeybindingsCopy(language?: string | null): KeybindingsCopy {
  return resolveMarketingLanguage(language) === 'fr' ? keybindingsFr : keybindingsEn;
}

export function formatKeybindingsCopy(
  template: string,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

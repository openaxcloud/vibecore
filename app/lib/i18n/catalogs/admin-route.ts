export type AdminRouteTranslationKey = keyof typeof adminRouteCatalog.en;

export function translateAdminRoute(
  language: SupportedLanguage | 'en' | 'fr' | undefined,
  key: AdminRouteTranslationKey,
  values?: Readonly<Record<string, string | number>>,
): string {
  const locale = language === 'fr' ? 'fr' : 'en';

  const template =
    adminRouteCatalog[locale][key] ??
    adminRouteCatalog.en[key] ??
    adminRouteCatalog[locale]['admin.route.sectionUnavailable'];

  if (!values) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match,
  );
}

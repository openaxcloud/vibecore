export function getProjectDashboardActivityCopy(language?: string | null): ProjectDashboardActivityCopy {
  return normalizeSupportedLanguage(language) === 'fr' ? projectDashboardActivityFr : projectDashboardActivityEn;
}

export function formatProjectDashboardActivityCopy(template: string, values: Readonly<Record<string, string>>): string {
  return template.replace(/\{(\w+)\}/gu, (token, key: string) => values[key] ?? token);
}

const WORKSPACE_STATUS_KEYS = new Map<string, ProjectDashboardActivityKey>([
  ['starting', 'projectDashboard.status.starting'],
  ['pending', 'projectDashboard.status.pending'],
  ['running', 'projectDashboard.status.running'],
  ['ready', 'projectDashboard.status.ready'],
  ['stopping', 'projectDashboard.status.stopping'],
  ['stopped', 'projectDashboard.status.stopped'],
  ['paused', 'projectDashboard.status.paused'],
  ['failed', 'projectDashboard.status.failed'],
  ['error', 'projectDashboard.status.error'],
  ['not_started', 'projectDashboard.status.notStarted'],
  ['not-started', 'projectDashboard.status.notStarted'],
]);

export function projectWorkspaceStatusLabel(status: string | null | undefined, language?: string | null): string {
  const copy = getProjectDashboardActivityCopy(language);

  if (!status) {
    return copy['projectDashboard.status.notStarted'];
  }

  const key = WORKSPACE_STATUS_KEYS.get(status.trim().toLowerCase()) ?? 'projectDashboard.status.unknown';

  return copy[key];
}


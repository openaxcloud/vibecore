const localeFor = (language: SupportedLanguage | undefined) => (language === 'fr' ? 'fr-FR' : 'en-GB');

export function billingMessage(
  language: SupportedLanguage | undefined,
  key: BillingMessageKey,
  values?: Readonly<Record<string, string | number>>,
): string {
  const template = (language === 'fr' ? billingFr : billingEn)[key];

  if (!values) {
    return template;
  }

  return template.replace(/\{(\w+)\}/gu, (match, token: string) =>
    Object.prototype.hasOwnProperty.call(values, token) ? String(values[token]) : match,
  );
}

export function billingLabelKey(value: string): BillingMessageKey | undefined {
  return LABEL_KEYS[value.trim().toLowerCase()];
}

export function billingDisplayName(
  value: string,
  language: SupportedLanguage | undefined = 'en',
  fallbackKey: BillingMessageKey = 'billing.label.recordedActivity',
): string {
  const key = billingLabelKey(value);

  if (key) {
    return billingMessage(language, key);
  }

  return language === 'fr' ? billingMessage(language, fallbackKey) : humanizeTechnicalIdentifier(value);
}

export function billingLedgerReason(reason: string, language: SupportedLanguage | undefined = 'en'): string {
  const normalized = reason.trim().toLowerCase();

  if (normalized === 'rollover cap exceeded') {
    return billingMessage(language, 'billing.history.rolloverExceeded');
  }

  if (normalized === 'prior grant expired (no rollover)') {
    return billingMessage(language, 'billing.history.priorGrantExpired');
  }

  const grant = /^(free|pro|team|enterprise|starter|business|scale) (\d{4}-\d{2}) grant$/u.exec(normalized);

  if (grant) {
    const period = new Intl.DateTimeFormat(localeFor(language), {
      month: 'long',
      year: 'numeric',
      timeZone: 'UTC',
    }).format(new Date(`${grant[2]}-01T00:00:00.000Z`));

    return billingMessage(language, 'billing.history.periodGrant', {
      plan: billingDisplayName(grant[1], language, 'billing.label.planAllowance'),
      period,
    });
  }

  // Administrators can enter free-form adjustment reasons; user-authored content is preserved verbatim.
  return reason;
}

export function formatBillingCurrency(
  cents: number,
  currency: string,
  language: SupportedLanguage | undefined = 'en',
  maximumFractionDigits = 2,
): string {
  const normalizedCurrency = /^[A-Za-z]{3}$/u.test(currency) ? currency.toUpperCase() : 'EUR';

  return new Intl.NumberFormat(localeFor(language), {
    style: 'currency',
    currency: normalizedCurrency,
    minimumFractionDigits: maximumFractionDigits,
    maximumFractionDigits,
  }).format(cents / 100);
}

export function formatBillingNumber(value: number, language: SupportedLanguage | undefined = 'en'): string {
  return new Intl.NumberFormat(localeFor(language)).format(value);
}

export function formatBillingDate(
  value: string,
  language: SupportedLanguage | undefined = 'en',
  includeTime = false,
): string {
  return new Intl.DateTimeFormat(localeFor(language), {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    ...(includeTime
      ? {
          hour: '2-digit',
          minute: '2-digit',
          hourCycle: 'h23' as const,
          timeZoneName: 'short' as const,
        }
      : {}),
    timeZone: 'UTC',
  }).format(new Date(value));
}

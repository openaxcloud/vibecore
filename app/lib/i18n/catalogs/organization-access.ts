export function getOrganizationAccessCopy(language?: string | null): OrganizationAccessCopy {
  return resolveMarketingLanguage(language) === 'fr' ? organizationAccessFr : organizationAccessEn;
}

export function formatOrganizationAccessCopy(
  template: string,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function formatOrganizationAccessDateTime(value: string | Date, language?: string | null): string {
  const date = value instanceof Date ? value : new Date(value);

  if (Number.isNaN(date.getTime())) {
    return String(value);
  }

  return new Intl.DateTimeFormat(resolveMarketingLanguage(language) === 'fr' ? 'fr-FR' : 'en-GB', {
    dateStyle: 'medium',
    timeStyle: 'short',
    timeZone: 'UTC',
  }).format(date);
}

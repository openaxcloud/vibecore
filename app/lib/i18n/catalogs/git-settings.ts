export function getGitSettingsCopy(language?: string | null): GitSettingsCopy {
  return resolveMarketingLanguage(language) === 'fr' ? gitSettingsFr : gitSettingsEn;
}

export function formatGitSettingsCopy(
  template: string,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function getGitSettingsErrorMessage(
  language: string | null | undefined,
  error: unknown,
  localizedFallback: string,
): string {
  if (resolveMarketingLanguage(language) === 'fr') {
    return localizedFallback;
  }

  return error instanceof Error && error.message ? error.message : localizedFallback;
}

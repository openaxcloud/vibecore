export function getProjectIdeCopy(language?: string | null): ProjectIdeCopy {
  return resolveMarketingLanguage(language) === 'fr' ? projectIdeFr : projectIdeEn;
}

export function formatProjectIdeCopy(template: string, values: Readonly<Record<string, string | number>> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function formatProjectIdeCount(
  copy: ProjectIdeCopy,
  singularKey: ProjectIdeKey,
  pluralKey: ProjectIdeKey,
  count: number,
): string {
  return formatProjectIdeCopy(copy[count === 1 ? singularKey : pluralKey], { count });
}

export function formatProjectIdeDateTime(value: Date, language?: string | null): string {
  return new Intl.DateTimeFormat(resolveMarketingLanguage(language) === 'fr' ? 'fr-FR' : 'en-US', {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(value);
}

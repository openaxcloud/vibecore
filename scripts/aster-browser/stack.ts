import assert from 'node:assert/strict';
import { recipeManifests } from '@recipe/private-runtime-recipe/manifests.js';

type Deployment = {
  apiVersion: string;
  kind: string;
  metadata: { name: string; namespace: string; labels: Record<string, string> };
  spec: {
    selector: { matchLabels: Record<string, string> };
    template: {
      metadata: { labels: Record<string, string> };
      spec: {
        serviceAccountName: string;
        automountServiceAccountToken: boolean;
        containers: {
          name: string;
          command: string[];
          env: { name: string; value: string }[];
          ports: { containerPort: number }[];
          readinessProbe: unknown;
        }[];
      };
    };
  };
};

/** Fresh bench manifests only. Keys are generated by run.ts, never supplied from outside. */
export function browserStack(resources: ReturnType<typeof recipeManifests>, tenantKey: string, proxyKey: string) {
  assert.match(tenantKey, /^[a-f0-9]{64}$/);
  assert.match(proxyKey, /^[a-f0-9]{64}$/);
  assert.notEqual(tenantKey, proxyKey);

  const result = structuredClone(resources);
  const secret = result.find((r) => r.kind === 'Secret');
  assert.ok(secret && 'stringData' in secret && secret.stringData);
  Object.assign(secret.stringData, { PREVIEW_TENANT_SECRET: tenantKey, PREVIEW_PROXY_SHARED_SECRET: proxyKey });

  const deployment = (name: string) => {
    const value = result.find((r) => r.kind === 'Deployment' && r.metadata.name === name);
    assert.ok(value);

    return value as unknown as Deployment;
  };
  deployment('manager').spec.template.spec.containers[0].env.push({
    name: 'WORKSPACE_MANAGER_ENFORCE_PREVIEW_TENANT',
    value: 'true',
  });
  deployment('api').spec.template.spec.containers[0].env.push({
    name: 'PREVIEW_URL_TEMPLATE',
    value: 'http://127.0.0.1:3020/p/{workspaceId}/{port}/',
  });

  const proxy = structuredClone(deployment('manager'));
  proxy.metadata.name = 'preview';
  proxy.spec.selector.matchLabels = { app: 'preview' };
  proxy.spec.template.metadata.labels.app = 'preview';
  proxy.spec.template.spec.serviceAccountName = 'default';
  proxy.spec.template.spec.automountServiceAccountToken = false;

  const container = proxy.spec.template.spec.containers[0];
  container.name = 'preview';
  container.command = ['pnpm', '--filter', '@vibecore/preview-proxy', 'exec', 'tsx', 'src/server.ts'];
  container.ports = [{ containerPort: 3020 }];
  container.readinessProbe = { tcpSocket: { port: 3020 }, periodSeconds: 3, timeoutSeconds: 5 };
  container.env = Object.entries({
    NODE_ENV: 'test',
    API_BASE_URL: 'http://api:3001',
    WORKSPACE_MANAGER_URL: 'http://manager:3010',
    PREVIEW_PROXY_PORT: '3020',
    PREVIEW_PROXY_ENFORCE_TENANT: 'true',
    PREVIEW_ENFORCE_PRIVATE_PORTS: 'true',
  }).map(([name, value]) => ({ name, value }));

  const service = structuredClone(result.find((r) => r.kind === 'Service' && r.metadata.name === 'manager'));
  assert.ok(service && 'spec' in service && service.spec && 'ports' in service.spec);
  service.metadata.name = 'preview';
  service.spec.selector = { app: 'preview' };
  service.spec.ports = [{ port: 3020, targetPort: 3020 }];

  return [...result, proxy, service];
}

const README_MD = `# Authentication (generated by E-Code "Add Authentication")

Real email/password auth backed by this project's Postgres (\`DATABASE_URL\`).

## 1. Install dependencies
\`\`\`
npm i pg bcryptjs jsonwebtoken cookie-parser
\`\`\`

## 2. Run the migration
\`\`\`
psql "$DATABASE_URL" -f db/migrations/0001_create_users.sql
\`\`\`

## 3. Mount the router (Express)
\`\`\`js
const cookieParser = require('cookie-parser');
const auth = require('./auth');

app.use(cookieParser());
app.use(auth.router); // POST /auth/signup, /auth/login, /auth/logout; GET /auth/me

// Protect a route:
app.get('/private', auth.requireAuth, (req, res) => res.json({ user: req.user }));

// Serve the login page:
app.get('/login', (req, res) => res.sendFile(__dirname + '/auth/login.html'));
\`\`\`

## Env
- \`AUTH_JWT_SECRET\` — set automatically by the scaffold (signs the session JWT).
- \`AUTH_SESSION_COOKIE\` — optional cookie name (default \`ecode_session\`).

Sessions are httpOnly JWT cookies (7-day expiry). Not a framework other than
Express? The same logic ports directly — swap the router for your framework's
equivalent; the Postgres queries and JWT helpers are unchanged.
`;

